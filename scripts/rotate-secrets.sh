#!/usr/bin/env bash
# =============================================================================
# rotate-secrets.sh — Generate fresh secrets for local development
# =============================================================================
# This script creates a new services/api/.env and apps/web/.env.local
# with strong random values for all secret fields.
#
# Usage:
#   ./scripts/rotate-secrets.sh
#
# ⚠️  This overwrites existing .env files. Back up first if needed.
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"

echo "🔐 Generating fresh secrets for Podacium local development..."
echo ""

# Generate random values
JWT_SECRET=$(openssl rand -hex 64)
SECRET_KEY=$(openssl rand -hex 32)
OAUTH_STATE_SECRET=$(openssl rand -hex 32)
NEXTAUTH_SECRET=$(openssl rand -base64 32)
POSTGRES_PASSWORD=$(openssl rand -hex 16)

# =============================================================================
# Backend .env
# =============================================================================
API_ENV="$ROOT_DIR/services/api/.env"

cat > "$API_ENV" << EOF
# =============================================================================
# PODACIUM API — Local Development Environment
# Generated by scripts/rotate-secrets.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# ⚠️  DO NOT COMMIT THIS FILE
# =============================================================================

# Database (local Docker Compose PostgreSQL)
DATABASE_URL="postgresql://podacium:${POSTGRES_PASSWORD}@localhost:5432/podacium"
PORT=8000

# JWT Authentication
JWT_SECRET_KEY="${JWT_SECRET}"
JWT_ALGORITHM=HS256
JWT_ACCESS_TOKEN_EXPIRE_MINUTES=30
JWT_REFRESH_TOKEN_EXPIRE_DAYS=7

# OAuth Providers (register at each provider's developer console)
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=
GOOGLE_REDIRECT_URI=http://localhost:8000/api/auth/oauth/google/callback

GITHUB_CLIENT_ID=
GITHUB_CLIENT_SECRET=
GITHUB_REDIRECT_URI=http://localhost:8000/api/auth/oauth/github/callback

LINKEDIN_CLIENT_ID=
LINKEDIN_CLIENT_SECRET=
LINKEDIN_REDIRECT_URI=http://localhost:8000/api/auth/oauth/linkedin/callback

OAUTH_STATE_SECRET="${OAUTH_STATE_SECRET}"
FRONTEND_OAUTH_REDIRECT_URL=http://localhost:3001/auth/callback

# Security
SECRET_KEY="${SECRET_KEY}"
BCRYPT_ROUNDS=10
RESET_TOKEN_EXPIRE_HOURS=1
VERIFICATION_TOKEN_EXPIRE_HOURS=24

# Email SMTP (leave empty to disable email in dev)
SMTP_HOST=smtp.gmail.com
SMTP_PORT=587
SMTP_USER=
SMTP_PASSWORD=
SMTP_USE_SSL=false
FRONTEND_URL=http://localhost:3001

# Payment Configuration (mock for local dev)
PAYMENT_GATEWAY=mock
DEFAULT_CURRENCY=DZD
PLATFORM_COMMISSION_PERCENT=15
PAYMENT_SUCCESS_RATE=90
PAYMENT_DELAY_MS=500

# Chargily Pay (leave empty for local dev)
CHARGILY_API_KEY=
CHARGILY_SECRET_KEY=
CHARGILY_BASE_URL=https://pay.chargily.net/api/v2
# Chargily uses the Secret Key for webhook HMAC signatures — set this to the same value as CHARGILY_SECRET_KEY
CHARGILY_WEBHOOK_SECRET=
CHARGILY_MODE=test

# WhatsApp Business API (leave empty for local dev)
WHATSAPP_PHONE_NUMBER_ID=
WHATSAPP_ACCESS_TOKEN=

# Phone Verification
PHONE_VERIFICATION_CODE_LENGTH=6
PHONE_VERIFICATION_EXPIRE_MINUTES=10
PHONE_VERIFICATION_MAX_ATTEMPTS=3
PHONE_VERIFICATION_RATE_LIMIT_MINUTES=1
PHONE_VERIFICATION_TEMPLATE_NAME="your_template_name"

# Redis
REDIS_URL=redis://localhost:6379/0
CELERY_BROKER_URL=redis://localhost:6379/1
CELERY_RESULT_BACKEND=redis://localhost:6379/1

# CORS
CORS_ORIGINS=["http://localhost:3000", "http://localhost:3001"]

# Cookie domain (empty for localhost)
COOKIE_DOMAIN=

# Environment
ENVIRONMENT=development
BASE_URL=http://localhost:8000

# Docker Postgres (must match DATABASE_URL above)
POSTGRES_DB=podacium
POSTGRES_USER=podacium
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}

# Supabase Storage (optional — only for video CDN)
NEXT_PUBLIC_SUPABASE_URL=
NEXT_PUBLIC_SUPABASE_ANON_KEY=
SUPABASE_STORAGE_KEY=

# Sentry (optional)
SENTRY_DSN=
SENTRY_TRACES_SAMPLE_RATE=0.1
EOF

echo "✅ Created $API_ENV"

# =============================================================================
# Frontend .env.local
# =============================================================================
WEB_ENV="$ROOT_DIR/apps/web/.env.local"

cat > "$WEB_ENV" << EOF
# =============================================================================
# PODACIUM WEB — Local Development Environment
# Generated by scripts/rotate-secrets.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# ⚠️  DO NOT COMMIT THIS FILE
# =============================================================================

NEXT_PUBLIC_API_URL=http://localhost:8000
NEXT_PUBLIC_BASE_URL=http://localhost:3001

# OAuth (register at each provider's developer console)
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=
GITHUB_CLIENT_ID=
GITHUB_CLIENT_SECRET=
LINKEDIN_CLIENT_ID=
LINKEDIN_CLIENT_SECRET=

# NextAuth
NEXTAUTH_SECRET="${NEXTAUTH_SECRET}"
NEXTAUTH_URL=http://localhost:3001

# Supabase Storage (optional — only for video CDN, NOT database)
NEXT_PUBLIC_SUPABASE_URL=
NEXT_PUBLIC_SUPABASE_ANON_KEY=
SUPABASE_STORAGE_KEY=

# Feature Flags
NEXT_PUBLIC_ENABLE_HLS=true
NEXT_PUBLIC_ENABLE_AWS_VIDEO=false

# CloudFront CDN (optional)
NEXT_PUBLIC_CLOUDFRONT_DOMAIN=

# Sentry (optional)
NEXT_PUBLIC_SENTRY_DSN=
EOF

echo "✅ Created $WEB_ENV"

# =============================================================================
# Summary
# =============================================================================
echo ""
echo "════════════════════════════════════════════════════════════════════════"
echo "  🔐 SECRETS GENERATED SUCCESSFULLY"
echo "════════════════════════════════════════════════════════════════════════"
echo ""
echo "  Files created:"
echo "    • services/api/.env"
echo "    • apps/web/.env.local"
echo ""
echo "  PostgreSQL password: ${POSTGRES_PASSWORD}"
echo "  (also set in DATABASE_URL and POSTGRES_PASSWORD)"
echo ""
echo "  Next steps:"
echo "    1. Update docker-compose.yml POSTGRES_PASSWORD if needed"
echo "    2. Run: docker compose up -d postgres redis"
echo "    3. Run: make dev-api"
echo "    4. Run: make dev-web"
echo ""
echo "  ⚠️  These files are in .gitignore and will NOT be committed."
echo "════════════════════════════════════════════════════════════════════════"
