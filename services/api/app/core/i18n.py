def normalize_locale(locale: str | None) -> str:
    """
    Normalizes any locale string into one of the supported 4: 'en', 'fr', 'ar', 'kab'.
    Defaults to 'en' if invalid or unsupported.
    """
    if not locale:
        return DEFAULT_LOCALE

    clean = locale.strip().lower().replace("_", "-")

    # Direct match or subtag match
    for supported in SUPPORTED_LOCALES:
        if clean == supported or clean.startswith(f"{supported}-"):
            return supported

    # Common aliases
    if clean.startswith("ar") or "arabic" in clean:
        return "ar"
    if clean.startswith("fr") or "french" in clean:
        return "fr"
    if clean.startswith("kab") or "taqbaylit" in clean or "ber" in clean:
        return "kab"

    return DEFAULT_LOCALE


def get_request_locale(request: Request) -> str:
    """
    Extracts preferred locale in prioritized order:
      1. Query param `lang` or `locale`
      2. Header `X-Locale`
      3. Cookie `locale`
      4. Header `Accept-Language`
      5. DEFAULT_LOCALE
    """
    # 1. Query param
    query_locale = request.query_params.get("lang") or request.query_params.get(
        "locale"
    )
    if query_locale and normalize_locale(query_locale) in SUPPORTED_LOCALES:
        return normalize_locale(query_locale)

    # 2. X-Locale header
    x_locale = request.headers.get("x-locale")
    if x_locale and normalize_locale(x_locale) in SUPPORTED_LOCALES:
        return normalize_locale(x_locale)

    # 3. Cookie
    cookie_locale = request.cookies.get("locale")
    if cookie_locale and normalize_locale(cookie_locale) in SUPPORTED_LOCALES:
        return normalize_locale(cookie_locale)

    # 4. Accept-Language header
    accept_lang = request.headers.get("accept-language")
    if accept_lang:
        # Parse tags like 'ar,en-US;q=0.9,fr;q=0.8'
        for part in accept_lang.split(","):
            raw_tag = part.split(";")[0].strip()
            norm = normalize_locale(raw_tag)
            if norm in SUPPORTED_LOCALES and any(
                raw_tag.lower().startswith(loc) for loc in SUPPORTED_LOCALES
            ):
                return norm

    return DEFAULT_LOCALE


def _localize_str_with_status(
    detail: str, locale: str = DEFAULT_LOCALE
) -> Tuple[str, str]:
    """
    Internal helper to localize a single string detail and return (message, error_code).
    """
    loc = normalize_locale(locale)
    cleaned = detail.strip()
    lower_detail = cleaned.lower()

    # 1. Exact lookup
    if lower_detail in TRANSLATIONS:
        entry = TRANSLATIONS[lower_detail]
        return entry.get(loc, entry.get("en", detail)), entry.get("code", "error")

    # 2. Fallback: Prefix matching for dynamic messages (e.g. Free preview limit reached)
    for key in sorted(TRANSLATIONS.keys(), key=len, reverse=True):
        if lower_detail.startswith(key):
            entry = TRANSLATIONS[key]
            # Replace prefix with localized prefix if matched
            matched_en = entry.get(loc, entry.get("en", key))
            remainder = cleaned[len(key) :]
            return f"{matched_en}{remainder}", entry.get("code", "error")

    # 3. Unmatched detail fallback
    # Generate fallback code from detail if it looks like an error identifier
    fallback_code = re.sub(r"[^a-zA-Z0-9_]", "_", lower_detail).strip("_")
    return detail, fallback_code or "error"


def localize_error(detail: Any, locale: str = DEFAULT_LOCALE) -> Tuple[Any, str]:
    """
    Translates any error detail structure (string, list, or dict) into the target locale.
    Returns a tuple of (localized_detail, error_code).
    """
    if isinstance(detail, str):
        return _localize_str_with_status(detail, locale)

    if isinstance(detail, dict):
        loc_dict = dict(detail)
        # Standard FastAPI/Pydantic error shapes
        if "detail" in loc_dict and isinstance(loc_dict["detail"], str):
            loc_msg, code = _localize_str_with_status(loc_dict["detail"], locale)
            loc_dict["detail"] = loc_msg
            loc_dict["message"] = loc_msg
            loc_dict["code"] = code
            return loc_dict, code
        if "message" in loc_dict and isinstance(loc_dict["message"], str):
            loc_msg, code = _localize_str_with_status(loc_dict["message"], locale)
            loc_dict["message"] = loc_msg
            loc_dict["code"] = code
            return loc_dict, code

        return loc_dict, loc_dict.get("code", "error")

    if isinstance(detail, list):
        # Localize array of sub-errors (e.g. Pydantic validation errors)
        loc_list = []
        primary_code = "validation_error"
        for item in detail:
            if (
                isinstance(item, dict)
                and "msg" in item
                and isinstance(item["msg"], str)
            ):
                item_copy = dict(item)
                loc_msg, _ = _localize_str_with_status(item["msg"], locale)
                item_copy["msg"] = loc_msg
                loc_list.append(item_copy)
            else:
                loc_list.append(item)
        return loc_list, primary_code

    return detail, "error"
