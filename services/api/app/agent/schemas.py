"""
services/api/app/agent/schemas.py
Canonical Pydantic v2 schemas for Model-Agnostic LLM Provider Abstraction.
"""

from enum import Enum
from typing import Dict, Any, List, Optional
from pydantic import BaseModel, Field


class Role(str, Enum):
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class FunctionCall(BaseModel):
    name: str = Field(..., description="Target tool or function name")
    arguments: Dict[str, Any] = Field(
        default_factory=dict, description="Parsed invocation arguments"
    )


class ToolCall(BaseModel):
    id: str = Field(..., description="Unique tool invocation ID")
    type: str = Field(default="function", description="Tool call type")
    function: FunctionCall = Field(..., description="Function call payload")
    thought_signature: Optional[str] = Field(
        default=None, description="Reasoning thought signature for Gemini models"
    )


class ChatMessage(BaseModel):
    role: Role = Field(..., description="Turn participant role")
    content: Optional[str] = Field(default=None, description="Textual message content")
    name: Optional[str] = Field(
        default=None, description="Optional author or tool name"
    )
    tool_call_id: Optional[str] = Field(
        default=None, description="ID referencing the invoked tool call"
    )
    tool_calls: Optional[List[ToolCall]] = Field(
        default=None, description="Tool calls generated by assistant"
    )
    raw_parts: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Original raw provider parts for faithful roundtripping",
    )


class ToolDefinition(BaseModel):
    name: str = Field(..., description="Tool identifier")
    description: str = Field(..., description="Semantic purpose of the tool")
    parameters: Dict[str, Any] = Field(
        ..., description="JSON Schema object defining tool parameters"
    )


class UsageMetadata(BaseModel):
    prompt_tokens: int = Field(default=0, description="Input tokens ingested")
    completion_tokens: int = Field(default=0, description="Output tokens generated")
    total_tokens: int = Field(default=0, description="Total tokens consumed")


class ChatCompletionRequest(BaseModel):
    messages: List[ChatMessage] = Field(
        ..., description="Chronological conversation turns"
    )
    tools: Optional[List[ToolDefinition]] = Field(
        default=None, description="Available callable tools"
    )
    temperature: float = Field(default=0.2, ge=0.0, le=2.0)
    max_tokens: Optional[int] = Field(default=2048, gt=0)
    top_p: Optional[float] = Field(default=0.95, ge=0.0, le=1.0)
    stream: bool = Field(default=False)
    stop: Optional[List[str]] = Field(default=None)


class ChatCompletionResponse(BaseModel):
    id: str = Field(..., description="Generation identifier")
    model: str = Field(..., description="Underlying model name")
    message: ChatMessage = Field(..., description="Assistant completion turn")
    finish_reason: str = Field(
        default="stop", description="Stop condition: stop, tool_calls, length"
    )
    usage: UsageMetadata = Field(default_factory=UsageMetadata)


class StreamingChunk(BaseModel):
    id: str = Field(..., description="Stream chunk identifier")
    delta_content: Optional[str] = Field(
        default=None, description="Incremental text fragment"
    )
    delta_tool_calls: Optional[List[ToolCall]] = Field(
        default=None, description="Incremental or completed tool calls"
    )
    finish_reason: Optional[str] = Field(
        default=None, description="Terminal status if stream ended"
    )
    usage: Optional[UsageMetadata] = Field(
        default=None, description="Final token counts if provided"
    )
    raw_parts: Optional[List[Dict[str, Any]]] = Field(
        default=None, description="Raw provider payload parts for roundtripping"
    )
